@dataclass(frozen=True, slots=True)
class Answer:
    """Один пункт меню: кнопка и то, что бот на неё отвечает."""

    key: str
    """Короткий ключ — уезжает в callback_data, поэтому только латиница."""

    button: str
    """Надпись на кнопке. Коротко: длинные не влезают в ширину экрана."""

    text: str
    """Сам ответ."""

    disclaimer: bool = False
    """Дописать ли приписку про ИИР. Нужна там, где речь о рынке и результатах."""

    def body(self) -> str:
        return self.text + (DISCLAIMER if self.disclaimer else "")


