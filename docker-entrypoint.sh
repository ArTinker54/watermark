#!/bin/sh
# Том с базой и пристинными оригиналами монтируется уже после сборки образа,
# и права на нём задаёт хост. Railway отдаёт точку монтирования root'у, поэтому
# процесс под непривилегированным пользователем не может даже создать файл базы
# ("unable to open database file"). Здесь владелец правится, пока права ещё есть,
# и только потом привилегии сбрасываются.
#
# Скрипт безопасно вызывать вложенно: если мы уже не root, он просто запускает
# команду. Это важно для хостингов, которые подставляют свой start command.
set -e

DATA_DIR="$(dirname "${DB_PATH:-/data/db.sqlite3}")"
STORAGE_DIR="${STORAGE_PATH:-/data/storage}"

if [ "$(id -u)" = "0" ]; then
    mkdir -p "$DATA_DIR" "$STORAGE_DIR"
    # Рекурсивный chown по всему хранилищу на каждом старте не нужен —
    # проверяем владельца корня и правим только когда он чужой.
    if [ "$(stat -c %u "$DATA_DIR")" != "1000" ]; then
        chown -R bot:bot "$DATA_DIR" "$STORAGE_DIR"
    fi
    exec gosu bot "$@"
fi

exec "$@"
